#!/bin/sh
# help.sh (Docker版) — run.sh 帮助文本（V10.10.21 自 run.sh 拆出，内容保持不变）
# 依赖：bin/common.sh（echo_e 与颜色变量）、bin/config.sh（默认值描述的上下文）

show_help() {
    echo_e "用法: $0 {start|stop|restart|status|logs|build|clean|add_nginx} [选项...]"
    echo ""
    echo_e "  ${GREEN}start${NC}     : 启动并部署 Docker 容器集群 (自动生成证书/配置 Nginx SNI 与清理缓存)"
    echo_e "  ${GREEN}stop${NC}      : 停止并移除 Docker 容器集群"
    echo_e "  ${GREEN}restart${NC}   : 重启 Docker 容器集群"
    echo_e "  ${GREEN}status${NC}    : 查看 Docker 容器运行状态 (运行中附带访问地址与数据库模式)"
    echo_e "  ${GREEN}logs${NC}      : 实时查看 Docker 容器日志"
    echo_e "  ${GREEN}build${NC}     : 重新构建 Docker 镜像"
    echo_e "  ${GREEN}clean${NC}     : 仅手动清理垃圾缓存与压缩 .git"
    echo_e "  ${GREEN}add_nginx${NC} : 仅配置/更新 SSL 证书与 Nginx 反代并热重载 (免重启 Docker 容器)"
    echo ""
    echo_e "定时任务与无人值守模式 (V10.11.34 优化，支持 3 种典型使用场景):"
    echo_e "  1) 完全自适应模式 (Crontab 自身无 TTY，脚本全自动识别为定时任务并使用默认参数):"
    echo_e "     0 3 * * * cd /opt/mengya-local && ./run.sh restart >> /var/log/mengya_cron.log 2>&1"
    echo_e "  2) 显式语义化模式 (推荐，意图最明确):"
    echo_e "     0 3 * * * cd /opt/mengya-local && ./run.sh restart --cron >> /var/log/mengya_cron.log 2>&1"
    echo_e "  3) 按需强制更新模式 (如定时每月强制轮换证书并热重载 Nginx，免重启后端):"
    echo_e "     0 0 1 * * cd /opt/mengya-local && ./run.sh add_nginx --cron --renew-ssl >> /var/log/mengya_ssl.log 2>&1"
    echo ""
    echo_e "可选命令行参数 (支持任意组合与顺序):"
    echo_e "  ${GREEN}--cron${NC} / ${GREEN}--unattended${NC}  无人值守模式，所有交互一律使用默认参数，不阻塞等待输入"
    echo_e "  ${GREEN}--renew-ssl${NC}            强制更新/重新生成 SSL 证书 (等价 SSL_FORCE_UPDATE=1)"
    echo_e "  ${GREEN}--renew-nginx${NC}          强制重新渲染并覆盖 Nginx 配置文件 (等价 NGINX_CONF_FORCE_UPDATE=1)"
    echo_e "  ${GREEN}--reconfig${NC}             清除已保存的数据库配置并重新选择"
    echo ""
    echo_e "多项目共用 443 端口（SNI 分流）环境变量:"
    echo_e "  PROJECT_NAME        项目标识 (默认: gift_app_docker)"
    echo_e "  SNI_DOMAIN          SNI 域名 (默认: localhost)"
    echo_e "  NGINX_PORT          Nginx 对外监听端口 (默认: 443)"
    echo_e "  SSL_FORCE_UPDATE=1          SSL 证书已存在时强制覆盖更新，不询问 (默认: 询问/无人值守时保留)"
    echo_e "  NGINX_CONF_FORCE_UPDATE=1   Nginx 配置已存在时强制覆盖渲染，不询问 (默认: 询问/无人值守时保留)"
    echo_e "  APP_IMAGE=ghcr.io/...:latest 预构建镜像地址 (非空时拉取镜像不本地构建，为空时本地 build)"
    echo_e "  GUNICORN_WORKERS=2           Gunicorn worker 数量 (默认 2，可调 1/4)"
    echo ""
    echo_e "
数据库部署选择 (首次 start 交互式三选一，选择结果持久化于 .temp/.db.env，后续 start/restart 自动读取):"
    echo_e "  ${GREEN}DB_MODE=sqlite|shared|independent${NC}   直接指定数据库模式跳过交互 (shared 需搭配 DB_PG_CONTAINER)"
    echo_e "  ${GREEN}DB_PG_CONTAINER=<容器名>${NC}            共享 PG 模式复用的已运行容器名，启动时自动接入自有网络 gift-docker_net"
    echo_e "  ${GREEN}--reconfig${NC} / ${GREEN}--reconfig-db${NC}        清除已保存的数据库配置并重新进入交互选择"
    echo_e "                                           用法: ./$(basename "$0") restart --reconfig   # 重选后 restart"
    echo_e "                                                 ./$(basename "$0") start --reconfig    # 重选后 start"
    echo_e "  ${GREEN}PG_IMAGE=<镜像名:版本>${NC}               独立 PG 模式自定义镜像版本"
    echo_e "                                           优先级: PG_IMAGE 指定 > 本地已有 PG 镜像 > 自动下载默认 postgres:16-alpine"
    echo_e "                                           仅独立 PG 模式生效；共享 PG 模式复用已运行容器，不涉及镜像选择"
    echo_e "  ${GREEN}PG_USER / PG_PASSWORD / PG_DB${NC}         PG 连接参数自定义 (默认: gift_docker_user / gift_docker_pass / gift_docker_db；与传统版差异化隔离；密码建议在 bin/config.local.sh 覆盖)"
    echo_e "                                           密码请使用字母数字组合 (含单引号/空格会被拒绝，URL 特殊字符 @ : / # ? 会警告)"
    echo_e "  ${GREEN}PG_PORT${NC}                                PG 连接端口自定义 (默认 5432；仅共享模式生效，独立模式容器内固定 5432)"
    echo_e "  示例: ./$(basename "$0") restart --reconfig                                   # 重新交互选择数据库模式后 restart"
    echo_e "  示例: ./$(basename "$0") start --reconfig                                     # 重新交互选择后直接 start"
    echo_e "  示例: DB_MODE=independent PG_IMAGE=postgres:16-alpine ./$(basename "$0") start    # 直通独立 PG，指定 16-alpine 镜像"
    echo_e "  示例: DB_MODE=independent PG_IMAGE=pgvector/pgvector:pg18 ./$(basename "$0") start # 指定 PG18 镜像(挂载路径自动匹配 /var/lib/postgresql)"
    echo_e "  示例: ./$(basename "$0") start --reconfig DB_MODE=independent PG_IMAGE=postgres:15 # 清除旧配置重选 + 直通独立 PG + 指定 15 版镜像"
    echo_e "  示例: DB_MODE=shared DB_PG_CONTAINER=pgvector-18 PG_USER=myuser PG_PASSWORD=mypass123 PG_DB=mygift PG_PORT=5433 ./$(basename "$0") start"
    echo_e "                                             # 共享 PG + 自定义账号/密码/库名/端口"
}
